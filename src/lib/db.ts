// Helper to compute next billing date given frequency and billing day
export const computeNextBillingDate = (frequency: RecurringInvoiceFrequency, billingDay: number, fromDate: Date = new Date()): string => {
  const next = new Date(fromDate);
  const day = Math.min(Math.max(billingDay || 1, 1), 28); // Cap safely for all months
  
  if (frequency === 'Weekly') {
    next.setDate(next.getDate() + 7);
  } else if (frequency === 'Monthly') {
    next.setMonth(next.getMonth() + 1);
    next.setDate(day);
  } else if (frequency === 'Quarterly') {
    next.setMonth(next.getMonth() + 3);
    next.setDate(day);
  } else if (frequency === 'Yearly') {
    next.setFullYear(next.getFullYear() + 1);
    next.setDate(day);
  }
  return next.toISOString().split('T')[0];
};

