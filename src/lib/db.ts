// Helper to generate seed historical invoices for rich chart visualization
const generateSeedInvoices = (): Invoice[] => {
  const seedInvoices: Invoice[] = [];
  const now = new Date();
  
  const sampleItems = [
    { src: '1', pay: '1', acc: '1', pur: 'Factory refrigeration components procurement', amt: 320000 },
    { src: '2', pay: '4', acc: '3', pur: 'Workstation computers and monitor upgrades', amt: 185000 },
    { src: '3', pay: '4', acc: '3', pur: 'Network switches and patch cords for server rack', amt: 75000 },
    { src: '4', pay: '3', acc: '4', pur: 'Monthly electricity and power utility consumption', amt: 142000 },
    { src: '5', pay: '3', acc: '3', pur: 'AWS Cloud computing, backups and storage services', amt: 135000 },
    { src: '6', pay: '1', acc: '4', pur: 'Office facility lease advance and service charge', amt: 210000 },
  ];

  // Distribute over last 6 months (0 to 5 months ago)
  for (let m = 5; m >= 0; m--) {
    const d = new Date(now.getFullYear(), now.getMonth() - m, 12);
    const monthStr = d.toLocaleString('default', { month: 'short' }).toUpperCase();
    const year = d.getFullYear();
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    const dateStr = `${year}${month}${day}`;

    sampleItems.forEach((item, idx) => {
      // Small variation in amount
      const variation = (idx % 2 === 0 ? 1 : -1) * (m * 4500) + (idx * 3200);
      const finalAmt = Math.max(25000, item.amt + variation);
      const invDate = new Date(year, d.getMonth(), 5 + idx * 3).toISOString();
      const seqStr = String(idx + 1 + m * 6).padStart(6, '0');

      seedInvoices.push({
        id: `inv-seed-${m}-${idx}`,
        invoiceNumber: `INV-WAL-MIS-${dateStr}-${seqStr}`,
        date: invDate,
        expenseSourceId: item.src,
        paymentTypeId: item.pay,
        accountTitleId: item.acc,
        purpose: `${item.pur} - ${monthStr} ${year}`,
        amount: finalAmt,
        amountInWords: numberToWords(finalAmt),
        preparedById: '1',
        verifiedById: '1',
        approvedById: '2',
        receivedById: '1',
        status: 'Approved',
        sealCode: generateSealCode(),
        referenceCode: generateReferenceCode(),
        createdBy: '1',
        createdAt: invDate,
        updatedAt: invDate,
        remarks: 'Processed and reconciled in accordance with financial policies.'
      });
    });
  }

  return seedInvoices;
};

