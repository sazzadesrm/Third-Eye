const initDB = () => {
  const existingInvoices = localStorage.getItem('te_invoices');
  const parsedInvoices: Invoice[] = existingInvoices ? JSON.parse(existingInvoices) : [];

  if (!localStorage.getItem('thirdeye_db_initialized') || parsedInvoices.length < 5) {
    localStorage.setItem('te_users', JSON.stringify(initialUsers));
    localStorage.setItem('te_expense_sources', JSON.stringify(initialExpenseSources));
    localStorage.setItem('te_payment_types', JSON.stringify(initialPaymentTypes));
    localStorage.setItem('te_account_titles', JSON.stringify(initialAccountTitles));
    localStorage.setItem('te_people', JSON.stringify(initialPeople));
    
    // Seed invoices if none exist or only minimal
    const invoicesToSave = parsedInvoices.length >= 5 ? parsedInvoices : generateSeedInvoices();
    localStorage.setItem('te_invoices', JSON.stringify(invoicesToSave));
    
    localStorage.setItem('te_recurring_invoices', JSON.stringify(initialRecurringInvoices));
    localStorage.setItem('te_email_logs', JSON.stringify([]));
    localStorage.setItem('te_audit_logs', JSON.stringify([]));
    localStorage.setItem('te_notifications', JSON.stringify([
      { id: '1', userId: '1', title: 'System Initialization', message: 'Welcome to THIRD EYE ERP. Recurring invoices and automated schedules ready.', read: false, createdAt: new Date().toISOString() }
    ]));
    
    // Ensure settings has backup reminders
    const savedSettings = localStorage.getItem('te_settings');
    if (!savedSettings) {
      localStorage.setItem('te_settings', JSON.stringify(initialSettings));
    } else {
      const merged = { ...initialSettings, ...JSON.parse(savedSettings) };
      localStorage.setItem('te_settings', JSON.stringify(merged));
    }
    
    localStorage.setItem('thirdeye_db_initialized', 'true');
  } else {
    // Ensure recurring invoices table exists
    if (!localStorage.getItem('te_recurring_invoices')) {
      localStorage.setItem('te_recurring_invoices', JSON.stringify(initialRecurringInvoices));
    }
    // Ensure settings has branding
    const savedSettings = localStorage.getItem('te_settings');
    if (savedSettings) {
      const parsed = JSON.parse(savedSettings);
      if (!parsed.branding) {
        localStorage.setItem('te_settings', JSON.stringify({ ...initialSettings, ...parsed, branding: initialSettings.branding }));
      }
    }
  }
};

